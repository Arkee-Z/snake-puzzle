#!/usr/bin/env python3
"""Export validated atom text configs into the compact SPA1 file C can load."""

from __future__ import annotations

import argparse
import sys
from pathlib import Path

from atomlib import AtomError, load_atoms


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--atoms", default="assets/atoms", help="source atom directory")
    parser.add_argument("--output", default="build/atoms.spa", help="SPA1 destination")
    args = parser.parse_args()

    try:
        atoms = load_atoms(args.atoms)
    except (AtomError, OSError, ValueError) as exc:
        print(f"ERROR: {exc}", file=sys.stderr)
        return 1

    output = Path(args.output)
    output.parent.mkdir(parents=True, exist_ok=True)
    try:
        with output.open("w", encoding="utf-8", newline="\n") as handle:
            handle.write("SPA1\n")
            handle.write("# Generated by tools/export_atoms.py; do not edit by hand.\n")
            for atom in atoms:
                handle.write(
                    f"BEGIN {atom.name}|{atom.difficulty}|{atom.weight}|{atom.solution}\n"
                )
                for row in atom.rows:
                    handle.write(row + "\n")
                handle.write("END\n")
    except OSError as exc:
        print(f"ERROR: cannot write {output}: {exc}", file=sys.stderr)
        return 1

    print(f"Exported {len(atoms)} atoms to {output} "
          f"({output.stat().st_size} bytes, SPA1 compact config).")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
